"""Extract per-session calibration data to standalone JSON files.

Loads multical workspace + triangulation config for each session,
computes derived quantities (R_total, floor_level, arena geometry),
and serializes everything to JSON so the standalone paper repo
does not need freemat_vid_inference or multical.

Usage:
    python scripts/single_fm/extract_calibration_json.py

Output:
    configs/calibration_<session_id>.json per session
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict

import numpy as np

# Repo root
REPO_ROOT = Path(__file__).resolve().parent.parent

# Add repo root and freemat_vid_inference to path
sys.path.insert(0, str(REPO_ROOT))
sys.path.insert(0, str(REPO_ROOT / "freemat_vid_inference"))

from freemat.single_fm.data.session_loader import SingleFMSessionLoader  # noqa: E402


SESSION_YAMLS = [
    "configs/session_M2_0526.yaml",
    "configs/session_M2_0605.yaml",
    "configs/session_M1_0525.yaml",
    "configs/session_M1_0609.yaml",
    "configs/session_M1_0613.yaml",
]


def _ndarray_to_list(obj: Any) -> Any:
    """Recursively convert numpy arrays to lists for JSON serialization."""
    if isinstance(obj, np.ndarray):
        return obj.tolist()
    if isinstance(obj, (np.float32, np.float64)):
        return float(obj)
    if isinstance(obj, (np.int32, np.int64)):
        return int(obj)
    if isinstance(obj, dict):
        return {k: _ndarray_to_list(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_ndarray_to_list(v) for v in obj]
    return obj


def serialize_arena(arena: Any) -> Dict:
    """Serialize ArenaGeometry to a JSON-compatible dict.

    Captures all state needed to reconstruct the geometry:
    - center, hexagon_radius, hexagon_vertices
    - floor_height, ceiling_height, up_axis
    - per-wall: normal, offset, point_on_plane, vertices
    """
    walls = {}
    for wall_id, wall in arena.walls.items():
        walls[wall_id] = {
            "normal": wall.normal.tolist(),
            "offset": float(wall.offset),
            "point_on_plane": wall.point_on_plane.tolist(),
            "vertices": _ndarray_to_list(wall.vertices) if wall.vertices is not None else None,
        }

    return {
        "center": arena.center.tolist(),
        "up_axis": arena.up_axis,
        "hexagon_radius": float(arena.hexagon_radius),
        "hexagon_vertices": arena.hexagon_vertices.tolist(),
        "floor_height": float(arena.floor_height),
        "ceiling_height": float(arena.ceiling_height),
        "n_walls": len(arena.walls),
        "walls": walls,
    }


def extract_session(yaml_path: str) -> Dict:
    """Extract all calibration-derived quantities for one session.

    Args:
        yaml_path: Relative path to session YAML from repo root.

    Returns:
        Dict with all calibration data, JSON-serializable.
    """
    full_path = str(REPO_ROOT / yaml_path)
    print(f"\n{'='*60}")
    print(f"Processing: {yaml_path}")

    loader = SingleFMSessionLoader(
        full_path,
        start_stop_tsv=str(REPO_ROOT / "docs" / "inf_start_stop_times.tsv"),
        banks_yaml=str(REPO_ROOT / "configs" / "banks.yaml"),
        canonical_alignment_path=str(
            REPO_ROOT / "configs" / "single_fm" / "canonical_alignment.json"
        ),
        debug=True,
    )

    # Trigger pose loading + rotation computation
    loader.get_pose_oriented()

    # Trigger arena geometry loading
    arena = loader.arena

    # Gather all derived quantities
    result = {
        "_comment": (
            "Pre-computed calibration for standalone paper repo. "
            "Generated by extract_calibration_json.py from freemat_os."
        ),
        "session_id": loader.session_id,
        "video_fps": float(loader.video_fps),
        "R_total": loader._R_total.tolist(),
        "t_total": loader._t_total.tolist() if loader._t_total is not None else None,
        "floor_level": float(loader._floor_level),
        "up_axis": loader._up_axis,
        "plane_dict": loader.plane_dict,
        "arena": serialize_arena(arena),
    }

    # Validation: check a few arena properties
    print(f"  session_id: {result['session_id']}")
    print(f"  video_fps: {result['video_fps']}")
    print(f"  floor_level: {result['floor_level']:.4f}")
    print(f"  up_axis: {result['up_axis']}")
    print(f"  R_total shape: (3,3), det={np.linalg.det(loader._R_total):.6f}")
    print(f"  t_total: {result['t_total']}")
    print(f"  arena center: {arena.center}")
    print(f"  arena radius: {arena.hexagon_radius:.4f}m")
    print(f"  arena walls: {len(arena.walls)}")
    print(f"  arena floor: {arena.floor_height:.4f}m")
    print(f"  arena ceiling: {arena.ceiling_height:.4f}m")

    return result


def main() -> None:
    """Extract calibration JSONs for all 5 sessions."""
    output_dir = REPO_ROOT / "configs" / "single_fm"

    results = {}
    for yaml_path in SESSION_YAMLS:
        try:
            data = extract_session(yaml_path)
            session_id = data["session_id"]
            out_path = output_dir / f"calibration_{session_id}.json"
            with open(out_path, "w") as f:
                json.dump(data, f, indent=2)
            print(f"  -> Saved: {out_path.relative_to(REPO_ROOT)}")
            results[session_id] = "OK"
        except Exception as e:
            print(f"  ERROR: {e}")
            import traceback
            traceback.print_exc()
            results[yaml_path] = f"FAILED: {e}"

    print(f"\n{'='*60}")
    print("Summary:")
    for k, v in results.items():
        print(f"  {k}: {v}")


if __name__ == "__main__":
    main()
